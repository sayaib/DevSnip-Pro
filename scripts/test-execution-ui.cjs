/* Requires an installed Playwright browser; exercises real renderer with controlled host replies. */
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..');
require('../out/test/unit/vscode-stub').installVscodeStub();
const { renderToolPage } = require('../out/toolkits/page');
const { EXECUTION_RUNTIME, EXECUTION_CSS } = require('../out/theme/execution');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    let html = renderToolPage({ cspSource: '', scriptUri: '', platform: 'linux', section: { id: 'test', title: 'Test' }, examples: [{ label: 'Sample', values: { text: 'sample' } }], initial: { text: 'imported' }, tool: {
      id: 'execution-test', live: true, title: 'Execution test', summary: 'Lifecycle fixture', fields: [{ id: 'text', label: 'Text', kind: 'text', default: 'hello' }]
    }}).replace(/<meta http-equiv="Content-Security-Policy"[^>]+>/, '').replace(/<script src=[^>]+><\/script>/, '');
    await page.setContent(html);
    await page.addStyleTag({ content: EXECUTION_CSS });
    await page.evaluate(() => { window.messages = []; window.acquireVsCodeApi = () => ({ getState: () => ({}), setState: () => {}, postMessage: m => window.messages.push(m) }); });
    await page.addScriptTag({ content: EXECUTION_RUNTIME });
    await page.addScriptTag({ content: fs.readFileSync(path.join(root, 'media/toolkit.js'), 'utf8') });
    const runs = () => page.evaluate(() => window.messages.filter(m => m.type === 'run').length);
    assert.equal(await runs(), 0, 'Defaults and imported input must not execute on load');
    await page.locator('#f_text').fill('typed');
    await page.locator('.presets').selectOption('0');
    await page.evaluate(() => {
      window.dispatchEvent(new MessageEvent('message', { data: { type: 'editorText', field: 'text', text: 'editor', source: 'editor' } }));
      window.dispatchEvent(new MessageEvent('message', { data: { type: 'setValues', values: { text: 'updated' }, run: true } }));
    });
    await page.waitForTimeout(450);
    assert.equal(await runs(), 0, 'Typing, presets, editor import and setValues must only populate inputs');
    const run = page.locator('.run-row .btn').first();
    const reply = async (id, extra = {}) => page.evaluate(({ id, extra }) => window.dispatchEvent(new MessageEvent('message', { data: { type: 'result', requestId: id, durationMs: 3, result: { outputs: [{ kind: 'text', title: 'Output', content: 'fresh output' }] }, ...extra } })), { id, extra });
    const id = async () => page.evaluate(() => window.messages.filter(m => m.type === 'run').at(-1).requestId);
    await run.click();
    assert(await run.isDisabled());
    assert.equal(await page.locator('.ds-execution').getAttribute('data-state'), 'running');
    await reply(await id());
    assert.equal(await page.locator('.ds-execution').getAttribute('data-state'), 'completed');
    assert(await page.locator('.ds-execution time').count());
    assert.equal(await page.locator('.ds-execution').getAttribute('data-fresh'), 'true');
    assert(await page.evaluate(() => document.getAnimations().some(a => a.id === 'ds-result-motion')), 'Fresh output must animate');
    await page.evaluate(() => {
      const host = document.getElementById('results');
      window.DevSnipExecution(host, 'completed', 'Completed', 1000);
      window.DevSnipExecution(host, 'completed', 'Completed', 1000);
    });
    assert.equal(await page.locator('.ds-execution').getAttribute('data-fresh'), 'false', 'Re-rendering old results must not replay freshness animation');
    assert.equal(await page.evaluate(() => document.getAnimations().filter(a => a.id === 'ds-result-motion').length), 0, 'Old receipts must cancel freshness motion');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('#f_text').fill('changed');
    assert.equal(await page.locator('.ds-execution').getAttribute('data-state'), 'stale');
    await run.click();
    assert((await page.locator('.ds-execution').textContent()).includes('previous run'));
    const second = await id();
    await reply(second - 1);
    assert.equal(await page.locator('.ds-execution').getAttribute('data-state'), 'running');
    await reply(second, { error: 'Network unavailable' });
    assert.equal(await page.locator('.ds-execution').getAttribute('data-state'), 'failed');
    assert((await page.locator('#results').textContent()).includes('Network unavailable'));
    await page.getByRole('button', { name: 'Run again', exact: true }).click();
    const pending = await id();
    await page.locator('.toolbar button').filter({ hasText: 'Reset' }).click();
    await reply(pending);
    assert.equal(await page.locator('.ds-execution').count(), 0, 'Reset must invalidate an in-flight reply');
    await run.click();
    await page.locator('#f_text').fill('changed during run');
    await reply(await id());
    assert.equal(await page.locator('.ds-execution').getAttribute('data-state'), 'stale');
    await page.getByRole('button', { name: 'Clear results', exact: true }).click();
    assert.equal(await page.locator('.ds-execution').count(), 0);
    const beforeLive = await runs();
    await page.getByRole('checkbox', { name: 'Live preview', exact: true }).check();
    assert.equal(await runs(), beforeLive, 'Enabling live mode alone must not generate output');
    await page.locator('#f_text').fill('live edit');
    await page.waitForTimeout(450);
    assert.equal(await runs(), beforeLive + 1, 'Explicitly opted-in live preview must still work');
    await reply(await id());
    assert.equal(await page.evaluate(() => document.getAnimations().filter(a => a.id === 'ds-result-motion').length), 0, 'Reduced motion disables output animations');
    await page.getByRole('checkbox', { name: 'Live preview', exact: true }).uncheck();
    await page.locator('#f_text').fill('manual again');
    await page.waitForTimeout(450);
    assert.equal(await runs(), beforeLive + 1);
    await page.setViewportSize({ width: 375, height: 812 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    const api = await browser.newPage();
    api.on('pageerror', e => errors.push(e.message));
    await api.evaluate(() => { window.acquireVsCodeApi = () => ({ getState: () => ({}), setState: () => {}, postMessage: () => {} }); });
    await api.addScriptTag({ content: EXECUTION_RUNTIME });
    const { getWebviewContent } = require('../out/commands/api-test');
    const apiHtml = getWebviewContent([], false).replace(/<meta http-equiv="Content-Security-Policy"[^>]+>/, '');
    await api.setContent(apiHtml);
    await api.locator('#url').fill('https://example.test');
    await api.locator('#sendRequest').click();
    assert.equal(await api.locator('.ds-execution').getAttribute('data-state'), 'running');
    await api.evaluate(() => window.dispatchEvent(new MessageEvent('message', { data: { command: 'apiResponse', status: 200, statusText: 'OK', data: { fresh: true }, headers: {}, responseTime: 10, size: 14 } })));
    assert.equal(await api.locator('.ds-execution').getAttribute('data-state'), 'completed');
    assert(!(await api.locator('#responseOutput').textContent()).includes('Completed'), 'Status must not contaminate response content');
    await api.locator('#sendRequest').click();
    await api.evaluate(() => window.dispatchEvent(new MessageEvent('message', { data: { command: 'apiError', title: 'Connection failed', error: 'Offline' } })));
    assert.equal(await api.locator('.ds-execution').getAttribute('data-state'), 'failed');
    assert.deepEqual(errors, []);
    console.log('Execution UI passed: actual start/reply, failure, stale inputs, late replies, reset, clear, timestamp and mobile layout.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
