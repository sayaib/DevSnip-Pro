/**
 * A strict, dependency-free XML 1.0 parser with namespaces.
 *
 * It checks well-formedness the way conforming parsers do and stops at the
 * first error with its line and column and a hint at the usual fix. It is a
 * single pass over the text with an explicit element stack, so deep nesting
 * cannot overflow the call stack and large documents parse in linear time.
 *
 * Supported: the XML declaration, DOCTYPE with internal entity declarations,
 * elements, attributes (normalised as the spec requires), namespaces
 * (declared, scoped and resolved), text with the five predefined entities and
 * character references, CDATA sections, comments and processing instructions.
 * External DTDs are never fetched.
 */

export interface XmlDeclaration {
  version: string;
  encoding?: string;
  standalone?: string;
}

export interface XmlElement {
  type: "element";
  /** Qualified name as written, e.g. "soap:Envelope". */
  name: string;
  /** Resolved namespace URI, when the element is in one. */
  namespace?: string;
  /** In document order; names are unique. */
  attributes: Array<[string, string]>;
  children: XmlNode[];
  /** xml:space="preserve" applies (inherited). */
  preserveSpace?: boolean;
}

export type XmlNode =
  | XmlElement
  | { type: "text"; value: string }
  | { type: "cdata"; value: string }
  | { type: "comment"; value: string }
  | { type: "instruction"; target: string; data: string }
  | { type: "doctype"; value: string };

export interface XmlDocument {
  declaration?: XmlDeclaration;
  /** Prolog and epilog nodes and the root element, in order. */
  children: XmlNode[];
  root: XmlElement;
}

export interface XmlStats {
  elements: number;
  attributes: number;
  textNodes: number;
  cdata: number;
  comments: number;
  instructions: number;
  namespaces: number;
  maxDepth: number;
}

export interface XmlWarning {
  message: string;
  line: number;
  column: number;
}

export class XmlSyntaxError extends Error {
  constructor(message: string, readonly line: number, readonly column: number, readonly offset: number, readonly hint?: string) {
    super(message);
    this.name = "XmlSyntaxError";
  }
}

export const XML_NS = "http://www.w3.org/XML/1998/namespace";
export const XMLNS_NS = "http://www.w3.org/2000/xmlns/";
/** Elements may nest this deep; anything deeper is almost certainly generated by mistake (or an attack). */
export const MAX_DEPTH = 5000;
/** Total characters entity references may expand to (the "billion laughs" guard). */
const MAX_ENTITY_EXPANSION = 10_000_000;

const START = ":A-Z_a-z\\u{C0}-\\u{D6}\\u{D8}-\\u{F6}\\u{F8}-\\u{2FF}\\u{370}-\\u{37D}\\u{37F}-\\u{1FFF}\\u{200C}-\\u{200D}\\u{2070}-\\u{218F}\\u{2C00}-\\u{2FEF}\\u{3001}-\\u{D7FF}\\u{F900}-\\u{FDCF}\\u{FDF0}-\\u{FFFD}\\u{10000}-\\u{EFFFF}";
const NAME_RE = new RegExp(`[${START}][${START}\\-.0-9\\u{B7}\\u{300}-\\u{36F}\\u{203F}-\\u{2040}]*`, "uy");
const NAME_FULL = new RegExp(`^[${START}][${START}\\-.0-9\\u{B7}\\u{300}-\\u{36F}\\u{203F}-\\u{2040}]*$`, "u");
// Characters XML 1.0 forbids anywhere, even as references.
const BAD_CHAR = /[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]|[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/;
const PREDEFINED: Record<string, string> = { lt: "<", gt: ">", amp: "&", quot: '"', apos: "'" };
// HTML entities people paste into XML, with the reference that works everywhere.
const HTML_ENTITIES: Record<string, number> = { nbsp: 160, copy: 169, reg: 174, trade: 8482, hellip: 8230, mdash: 8212, ndash: 8211, laquo: 171, raquo: 187, euro: 8364, pound: 163, yen: 165, cent: 162, deg: 176, times: 215, divide: 247, middot: 183, bull: 8226, lsquo: 8216, rsquo: 8217, ldquo: 8220, rdquo: 8221, eacute: 233, egrave: 232, auml: 228, ouml: 246, uuml: 252, szlig: 223, ccedil: 231, ntilde: 241 };

const isSpace = (c: string | undefined) => c === " " || c === "\t" || c === "\n" || c === "\r";

export interface ParseResult {
  document: XmlDocument;
  stats: XmlStats;
  warnings: XmlWarning[];
}

interface OpenElement {
  element: XmlElement;
  start: number;
  scope: Map<string, string>;
}

/** Parses XML text. Throws XmlSyntaxError (with line and column) for the first well-formedness error. */
export function parseXml(input: string): ParseResult {
  // The spec normalises line endings before parsing; offsets refer to this text.
  const s = input.replace(/\r\n?/g, "\n");
  const len = s.length;
  let lineStarts: number[] | undefined;
  const position = (offset: number) => {
    if (!lineStarts) {
      lineStarts = [0];
      for (let i = s.indexOf("\n"); i !== -1; i = s.indexOf("\n", i + 1)) lineStarts.push(i + 1);
    }
    let lo = 0, hi = lineStarts.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (lineStarts[mid] <= offset) lo = mid; else hi = mid - 1;
    }
    return { line: lo + 1, column: offset - lineStarts[lo] + 1 };
  };
  const fail = (offset: number, message: string, hint?: string): never => {
    const { line, column } = position(Math.min(offset, len));
    throw new XmlSyntaxError(message, line, column, offset, hint);
  };
  const warnings: XmlWarning[] = [];
  const warn = (offset: number, message: string) => {
    if (warnings.length >= 50 || warnings.some(w => w.message === message)) return;
    warnings.push({ message, ...position(offset) });
  };
  const at = (offset: number) => { const p = position(offset); return `line ${p.line}, column ${p.column}`; };

  const bad = BAD_CHAR.exec(s);
  if (bad && bad.index < 64 && !s.trimStart().startsWith("<")) {
    // Binary data, not text: say so instead of naming one odd character.
    fail(0, s.startsWith("bplist") ? "This is a binary property list, not XML text." : "This looks like a binary file, not XML text.",
      s.startsWith("bplist") ? "Convert it to XML first, e.g. plutil -convert xml1 file.plist." : "Open an XML file (text starting with < ), or check the file's encoding.");
  }
  if (bad) fail(bad.index, `The character U+${bad[0].charCodeAt(0).toString(16).toUpperCase().padStart(4, "0")} isn't allowed in XML.`, "Remove it; control characters can't appear in XML 1.0, not even as &#…; references.");

  const stats: XmlStats = { elements: 0, attributes: 0, textNodes: 0, cdata: 0, comments: 0, instructions: 0, namespaces: 0, maxDepth: 0 };
  const children: XmlNode[] = [];
  const stack: OpenElement[] = [];
  const entities = new Map<string, string>();
  let externalDtd = false;
  let declaration: XmlDeclaration | undefined;
  let root: XmlElement | undefined;
  let rootClosedAt = -1;
  let doctypeSeen = false;
  let expanded = 0;
  let pos = s.charCodeAt(0) === 0xfeff ? 1 : 0;

  const readName = (from: number, what: string): string => {
    NAME_RE.lastIndex = from;
    const m = NAME_RE.exec(s);
    if (!m) {
      const c = s[from];
      if (c === undefined) fail(from, `The document ends where ${what} was expected.`);
      if (/[0-9.-]/.test(c)) fail(from, `${capital(what)} can't start with "${c}".`, "XML names start with a letter, \"_\" or \":\".");
      if (isSpace(c)) fail(from, `Expected ${what} but found whitespace.`, what.includes("element") ? "Write the name right after \"<\", e.g. <item>, not < item>." : undefined);
      fail(from, `Expected ${what} but found "${c}".`);
    }
    return m![0];
  };
  const skipSpace = (from: number) => { let i = from; while (isSpace(s[i])) i++; return i; };

  /** Replaces references in text or an attribute value. */
  const decode = (raw: string, offset: number, depth = 0): string => {
    if (raw.indexOf("&") === -1) return raw;
    let out = "";
    let last = 0;
    for (let i = raw.indexOf("&"); i !== -1; i = raw.indexOf("&", last)) {
      out += raw.slice(last, i);
      const end = raw.indexOf(";", i);
      const ref = end === -1 ? "" : raw.slice(i + 1, end);
      if (end === -1 || end - i > 64 || !(ref[0] === "#" ? /^#(?:[0-9]+|x[0-9a-fA-F]+)$/.test(ref) : NAME_FULL.test(ref))) {
        if (ref[0] === "#" && end !== -1) fail(offset + i, `&${ref}; isn't a valid character reference.`, "Write &#NNN; (decimal) or &#xHHH; (hexadecimal).");
        fail(offset + i, "\"&\" must start a reference such as &amp; or &#38;.", "To write a literal ampersand, use &amp;.");
      }
      if (ref[0] === "#") {
        const code = ref[1] === "x" ? parseInt(ref.slice(2), 16) : parseInt(ref.slice(1), 10);
        const ch = code > 0x10ffff || Number.isNaN(code) ? "" : String.fromCodePoint(code);
        if (!ch || BAD_CHAR.test(ch) || (code >= 0xd800 && code <= 0xdfff)) fail(offset + i, `&${ref}; refers to a character XML doesn't allow.`);
        out += ch;
      } else if (PREDEFINED[ref] !== undefined) {
        out += PREDEFINED[ref];
      } else if (entities.has(ref)) {
        if (depth > 8) fail(offset + i, `The entity &${ref}; refers to itself (directly or through other entities).`);
        const value = decode(entities.get(ref)!, offset + i, depth + 1);
        expanded += value.length;
        if (expanded > MAX_ENTITY_EXPANSION) fail(offset + i, "Entities expand to more than 10 million characters.", "This looks like an entity-expansion (\"billion laughs\") attack, so it was stopped.");
        if (value.includes("<")) warn(offset + i, `The entity &${ref}; contains markup; it is kept as text.`);
        out += value;
      } else if (externalDtd) {
        warn(offset + i, `&${ref}; is declared in an external DTD, which isn't read; it is kept as written.`);
        out += `&${ref};`;
      } else {
        const html = HTML_ENTITIES[ref];
        fail(offset + i, `The entity &${ref}; isn't defined.`, html
          ? `XML only knows &lt; &gt; &amp; &quot; and &apos;. &${ref}; is an HTML entity; write &#${html}; instead.`
          : "XML only knows &lt; &gt; &amp; &quot; and &apos; unless the DOCTYPE declares more.");
      }
      last = end + 1;
    }
    return out + raw.slice(last);
  };

  const add = (node: XmlNode) => {
    if (stack.length) stack[stack.length - 1].element.children.push(node);
    else children.push(node);
  };

  // ---------------------------------------------------------------- XML declaration
  if (s.startsWith("<?xml", pos) && (isSpace(s[pos + 5]) || s[pos + 5] === "?")) {
    const end = s.indexOf("?>", pos);
    if (end === -1) fail(pos, "The XML declaration is never closed with \"?>\".");
    const body = s.slice(pos + 5, end);
    const attrs: Array<[string, string]> = [];
    const re = /\s*([A-Za-z]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/y;
    let i = 0;
    for (;;) {
      re.lastIndex = i;
      const m = re.exec(body);
      if (!m) break;
      attrs.push([m[1], m[2] ?? m[3]]);
      i = re.lastIndex;
    }
    if (body.slice(i).trim()) fail(pos + 5 + i, `Unexpected "${body.slice(i).trim().slice(0, 20)}" in the XML declaration.`, "It looks like <?xml version=\"1.0\" encoding=\"UTF-8\"?>.");
    const names = attrs.map(a => a[0]);
    if (names[0] !== "version") fail(pos, "The XML declaration must start with version, e.g. <?xml version=\"1.0\"?>.");
    const order = ["version", "encoding", "standalone"];
    names.forEach((n, k) => { if (!order.includes(n) || (k > 0 && order.indexOf(n) <= order.indexOf(names[k - 1]))) fail(pos, `"${n}" is out of place in the XML declaration.`, "Only version, encoding and standalone are allowed, in that order."); });
    declaration = { version: attrs[0][1] };
    if (!/^1\.[0-9]+$/.test(declaration.version)) fail(pos, `Unsupported XML version "${declaration.version}".`);
    for (const [n, v] of attrs.slice(1)) {
      if (n === "encoding") {
        if (!/^[A-Za-z][A-Za-z0-9._-]*$/.test(v)) fail(pos, `"${v}" isn't a valid encoding name.`);
        declaration.encoding = v;
        try { new TextDecoder(v); } catch { warn(pos, `"${v}" isn't an encoding this converter knows; the text is used as it is.`); }
      } else {
        if (v !== "yes" && v !== "no") fail(pos, "standalone must be \"yes\" or \"no\".");
        declaration.standalone = v;
      }
    }
    pos = end + 2;
  }

  // ---------------------------------------------------------------- content
  while (pos < len) {
    const lt = s.indexOf("<", pos);
    if (lt !== pos) {
      // Text up to the next markup.
      const end = lt === -1 ? len : lt;
      const raw = s.slice(pos, end);
      if (!stack.length) {
        if (raw.trim()) {
          const first = pos + raw.search(/\S/);
          if (root) fail(first, "Text after the root element closed.", `Everything must be inside <${root.name}>, which closed on ${at(rootClosedAt)}.`);
          fail(first, "Text before the root element.", s.slice(first, first + 1) === "{" || s.slice(first, first + 1) === "[" ? "This looks like JSON, not XML." : "An XML document starts with an element such as <root>, optionally after <?xml …?>.");
        }
      } else {
        const cdataEnd = raw.indexOf("]]>");
        if (cdataEnd !== -1) fail(pos + cdataEnd, "\"]]>\" isn't allowed in text.", "Write ]]&gt; instead.");
        add({ type: "text", value: decode(raw, pos) });
        stats.textNodes++;
      }
      pos = end;
      continue;
    }

    if (s.startsWith("<!--", pos)) {
      const end = s.indexOf("-->", pos + 4);
      if (end === -1) fail(pos, "This comment is never closed with \"-->\".");
      const value = s.slice(pos + 4, end);
      const dash = value.indexOf("--");
      if (dash !== -1) fail(pos + 4 + dash, "\"--\" isn't allowed inside a comment.", "Comments can't contain two hyphens in a row.");
      if (value.endsWith("-")) fail(end - 1, "A comment can't end with \"--->\".");
      add({ type: "comment", value });
      stats.comments++;
      pos = end + 3;
      continue;
    }

    if (s.startsWith("<![CDATA[", pos)) {
      if (!stack.length) fail(pos, "A CDATA section must be inside an element.");
      const end = s.indexOf("]]>", pos + 9);
      if (end === -1) fail(pos, "This CDATA section is never closed with \"]]>\".");
      add({ type: "cdata", value: s.slice(pos + 9, end) });
      stats.cdata++;
      pos = end + 3;
      continue;
    }

    if (s.startsWith("<!DOCTYPE", pos)) {
      if (root || stack.length) fail(pos, "The DOCTYPE must come before the root element.");
      if (doctypeSeen) fail(pos, "Only one DOCTYPE is allowed.");
      doctypeSeen = true;
      let i = pos + 9, depth = 0, quote = "";
      for (; i < len; i++) {
        const c = s[i];
        if (quote) { if (c === quote) quote = ""; continue; }
        if (c === '"' || c === "'") quote = c;
        else if (c === "[") depth++;
        else if (c === "]") depth--;
        else if (c === ">" && depth <= 0) break;
      }
      if (i >= len) fail(pos, "The DOCTYPE is never closed with \">\".");
      const value = s.slice(pos, i + 1);
      checkDoctype(value, pos, fail);
      const subsetStart = value.indexOf("[");
      const head = subsetStart === -1 ? value : value.slice(0, subsetStart);
      if (/\b(SYSTEM|PUBLIC)\b/.test(head)) externalDtd = true;
      if (subsetStart !== -1) {
        const subset = value.slice(subsetStart + 1, value.lastIndexOf("]"));
        for (const m of subset.matchAll(/<!ENTITY\s+(%\s+)?([^\s]+)\s+(?:"([^"]*)"|'([^']*)'|(SYSTEM|PUBLIC)[^>]*)\s*>/g)) {
          if (m[1]) continue; // parameter entities only matter inside the DTD
          if (m[5]) { externalDtd = true; continue; }
          if (!entities.has(m[2])) entities.set(m[2], m[3] ?? m[4]);
        }
        if (/%[^\s;]+;/.test(subset)) externalDtd = true;
      }
      add({ type: "doctype", value });
      pos = i + 1;
      continue;
    }

    if (s.startsWith("<?", pos)) {
      const target = readName(pos + 2, "an instruction name");
      if (target.toLowerCase() === "xml") fail(pos, "The XML declaration is only allowed at the very start of the document.", pos > 0 && !s.slice(0, pos).trim() ? "Remove the whitespace or blank lines before <?xml." : "Remove this second declaration.");
      if (target.includes(":")) fail(pos + 2, `The instruction name "${target}" can't contain a colon.`, "With namespaces, instruction targets are plain names such as xml-stylesheet.");
      const end = s.indexOf("?>", pos);
      if (end === -1) fail(pos, `The instruction <?${target} is never closed with "?>".`);
      const afterName = pos + 2 + target.length;
      if (afterName < end && !isSpace(s[afterName])) fail(afterName, `Expected a space after <?${target}.`);
      add({ type: "instruction", target, data: s.slice(afterName, end).replace(/^\s+/, "") });
      stats.instructions++;
      pos = end + 2;
      continue;
    }

    if (s[pos + 1] === "/") {
      const name = readName(pos + 2, "an element name");
      const close = skipSpace(pos + 2 + name.length);
      if (s[close] !== ">") fail(close, `Expected ">" to end </${name}.`);
      const open = stack.pop();
      if (!open) {
        fail(pos, root ? `</${name}> comes after the root element <${root.name}> closed.` : `</${name}> has no matching <${name}>.`);
      } else if (open.element.name !== name) {
        const matching = stack.some(o => o.element.name === name);
        fail(pos, `</${name}> doesn't match <${open.element.name}>, opened on ${at(open.start)}.`, matching ? `Close <${open.element.name}> first with </${open.element.name}>, or end it with "/>".` : `Did you mean </${open.element.name}>?`);
      }
      if (!stack.length) rootClosedAt = pos;
      pos = close + 1;
      continue;
    }

    if (s[pos + 1] === "!") fail(pos, `Unknown markup "${s.slice(pos, pos + 12)}…".`, "Comments are <!-- … -->, CDATA sections <![CDATA[ … ]]> and the doctype <!DOCTYPE …>.");

    // Start tag.
    const name = readName(pos + 1, "an element name");
    if (root && !stack.length) fail(pos, `A second root element <${name}>.`, `An XML document has exactly one root element; <${root.name}> already closed on ${at(rootClosedAt)}. Wrap both in a single element.`);
    let i = pos + 1 + name.length;
    const attributes: Array<[string, string]> = [];
    const offsets: number[] = [];
    let selfClosing = false;
    for (;;) {
      const before = i;
      i = skipSpace(i);
      const c = s[i];
      if (c === ">") { i++; break; }
      if (c === "/" && s[i + 1] === ">") { selfClosing = true; i += 2; break; }
      if (c === undefined) fail(pos, `<${name}> is never closed with ">".`);
      if (c === "<") fail(i, `"<" inside the tag <${name}>: the tag is missing its ">".`);
      if (c === "=") fail(i, `Expected an attribute name before "=" in <${name}>.`);
      if (i === before) fail(i, `Expected a space before the next attribute in <${name}>.`);
      const attrName = readName(i, "an attribute name");
      const nameAt = i;
      i = skipSpace(i + attrName.length);
      if (s[i] !== "=") fail(i, `The attribute ${attrName} in <${name}> has no value.`, `XML attributes always have a quoted value, e.g. ${attrName}="${attrName}".`);
      i = skipSpace(i + 1);
      const q = s[i];
      if (q !== '"' && q !== "'") {
        const word = /^[^\s/>]*/.exec(s.slice(i))![0];
        fail(i, `The value of ${attrName} must be in quotes.`, `Write ${attrName}="${word}".`);
      }
      const end = s.indexOf(q, i + 1);
      if (end === -1) fail(i, `The value of ${attrName} is never closed with ${q}.`);
      const raw = s.slice(i + 1, end);
      const ltIn = raw.indexOf("<");
      if (ltIn !== -1) fail(i + 1 + ltIn, `"<" isn't allowed in the value of ${attrName}.`, "Write &lt; instead.");
      if (attributes.some(a => a[0] === attrName)) fail(nameAt, `The attribute ${attrName} appears twice in <${name}>.`);
      // Attribute-value normalisation: literal tabs and newlines become spaces; references stay as written.
      attributes.push([attrName, decode(raw.replace(/[\t\n]/g, " "), i + 1)]);
      offsets.push(nameAt);
      i = end + 1;
    }

    // Namespaces: declarations on this element apply to it and its attributes.
    const parentScope = stack.length ? stack[stack.length - 1].scope : undefined;
    // Scopes are shared down the tree until an element declares something, then copied.
    let scope = parentScope ?? new Map<string, string>([["xml", XML_NS]]);
    let owned = !parentScope;
    attributes.forEach(([attrName, value], k) => {
      if (attrName !== "xmlns" && !attrName.startsWith("xmlns:")) return;
      const prefix = attrName === "xmlns" ? "" : attrName.slice(6);
      if (prefix === "xmlns") fail(offsets[k], "The prefix xmlns can't be declared.");
      if (prefix === "xml" && value !== XML_NS) fail(offsets[k], "The prefix xml is reserved for the XML namespace.");
      if (prefix && prefix !== "xml" && value === XML_NS) fail(offsets[k], "Only the prefix xml may be bound to the XML namespace.");
      if (value === XMLNS_NS) fail(offsets[k], "Nothing may be bound to the xmlns namespace.");
      if (prefix && !value) fail(offsets[k], `xmlns:${prefix}="" isn't allowed: a prefix can't be undeclared in XML 1.0.`);
      if (!owned) { scope = new Map(scope); owned = true; }
      scope.set(prefix, value);
      stats.namespaces++;
    });
    const resolve = (qname: string, offset: number, isAttribute: boolean): string | undefined => {
      const colon = qname.indexOf(":");
      if (colon === 0 || qname.endsWith(":")) fail(offset, `"${qname}" isn't a valid name: a colon may only separate a prefix from a local name.`);
      if (colon === -1) return isAttribute ? undefined : scope.get("") || undefined;
      const prefix = qname.slice(0, colon);
      const local = qname.slice(colon + 1);
      if (!local || local.includes(":") || !NAME_FULL.test(local) || /^[0-9.-]/.test(local)) fail(offset, `"${qname}" isn't a valid qualified name.`, "Use at most one colon, as prefix:name.");
      if (prefix === "xmlns") return XMLNS_NS;
      const uri = scope.get(prefix);
      if (uri === undefined) fail(offset, `The namespace prefix "${prefix}" isn't declared.`, `Add xmlns:${prefix}="…" to this element or one of its parents.`);
      return uri;
    };
    const namespace = resolve(name, pos + 1, false);
    const expandedNames = new Set<string>();
    attributes.forEach(([attrName], k) => {
      if (attrName === "xmlns") return;
      const uri = resolve(attrName, offsets[k], true);
      if (uri) {
        const key = `{${uri}}${attrName.slice(attrName.indexOf(":") + 1)}`;
        if (expandedNames.has(key)) fail(offsets[k], `${attrName} duplicates another attribute in the same namespace.`);
        expandedNames.add(key);
      }
    });

    const parent = stack.length ? stack[stack.length - 1].element : undefined;
    const space = attributes.find(a => a[0] === "xml:space")?.[1];
    const element: XmlElement = { type: "element", name, attributes, children: [] };
    if (namespace) element.namespace = namespace;
    if (space === "preserve" || (space !== "default" && parent?.preserveSpace)) element.preserveSpace = true;
    add(element);
    stats.elements++;
    stats.attributes += attributes.length;
    if (!root) root = element;
    if (selfClosing) {
      if (!stack.length) rootClosedAt = pos;
    } else {
      stack.push({ element, start: pos, scope });
      if (stack.length > stats.maxDepth) stats.maxDepth = stack.length;
      if (stack.length > MAX_DEPTH) fail(pos, `Elements are nested more than ${MAX_DEPTH.toLocaleString("en-US")} levels deep.`);
    }
    if (selfClosing && stack.length + 1 > stats.maxDepth) stats.maxDepth = stack.length + 1;
    pos = i;
  }

  if (stack.length) {
    const open = stack[stack.length - 1];
    fail(len, `<${open.element.name}> is never closed (opened on ${at(open.start)}).`, `Add </${open.element.name}> before the end, or end the tag with "/>" if it has no content.`);
  }
  if (!root) {
    if (!s.replace(/^\uFEFF/, "").trim()) fail(0, "The document is empty.");
    fail(len, "No root element found.", "An XML document needs one element that contains everything else.");
  }
  return { document: { declaration, children, root: root! }, stats, warnings };
}

const QUOTED = `(?:"[^"]*"|'[^']*')`;
const NAME_SRC = NAME_RE.source;
const ENTITY_DECL = new RegExp(`^<!ENTITY\\s+(?:%\\s+)?${NAME_SRC}\\s+(?:${QUOTED}|(?:SYSTEM\\s+${QUOTED}|PUBLIC\\s+${QUOTED}\\s+${QUOTED})(?:\\s+NDATA\\s+${NAME_SRC})?)\\s*>$`, "u");
const EXTERNAL_ID = new RegExp(`^(?:SYSTEM\\s+${QUOTED}|PUBLIC\\s+${QUOTED}\\s+${QUOTED})$`, "u");

/**
 * Checks a DOCTYPE's shape: <!DOCTYPE name [ExternalID] [[internal subset]]>,
 * and that the internal subset holds only markup declarations, comments,
 * instructions and parameter-entity references. Element and attribute-list
 * declarations are checked for balance, not grammar; nothing is validated
 * against them.
 */
function checkDoctype(value: string, at: number, fail: (offset: number, message: string, hint?: string) => never): void {
  const head = /^<!DOCTYPE(\s+)/.exec(value);
  if (!head) fail(at + 9, "Expected a space and the root element's name after <!DOCTYPE.");
  NAME_RE.lastIndex = 0;
  const rest = value.slice(head![0].length);
  const name = new RegExp(`^${NAME_SRC}`, "u").exec(rest);
  if (!name) fail(at + head![0].length, "Expected the root element's name after <!DOCTYPE.");
  const subsetStart = value.indexOf("[");
  const between = value.slice(head![0].length + name![0].length, subsetStart === -1 ? value.length - 1 : subsetStart).trim();
  if (between && !EXTERNAL_ID.test(between)) fail(at + head![0].length + name![0].length, `Unexpected "${between.slice(0, 30)}" in the DOCTYPE.`, "After the name may come SYSTEM \"uri\" or PUBLIC \"id\" \"uri\", then an optional [internal subset].");
  if (subsetStart === -1) return;
  const close = value.lastIndexOf("]");
  if (close < subsetStart || value.slice(close + 1, -1).trim()) fail(at + close, "The DOCTYPE's internal subset must end with \"]\" right before \">\".");
  const subset = value.slice(subsetStart + 1, close);
  const base = at + subsetStart + 1;
  for (let i = 0; i < subset.length;) {
    if (isSpace(subset[i])) { i++; continue; }
    const from = i;
    if (subset.startsWith("<!--", i)) {
      const end = subset.indexOf("-->", i + 4);
      if (end === -1 || subset.slice(i + 4, end).includes("--")) fail(base + i, "A comment in the DOCTYPE isn't closed properly.");
      i = end + 3;
    } else if (subset.startsWith("<?", i)) {
      const end = subset.indexOf("?>", i);
      if (end === -1) fail(base + i, "An instruction in the DOCTYPE is never closed.");
      i = end + 2;
    } else if (subset[i] === "%") {
      const m = new RegExp(`^%${NAME_SRC};`, "u").exec(subset.slice(i));
      if (!m) fail(base + i, "A parameter-entity reference in the DOCTYPE must look like %name;.");
      i += m![0].length;
    } else if (/^<!(ENTITY|ELEMENT|ATTLIST|NOTATION)\s/.test(subset.slice(i, i + 12))) {
      let quote = "", j = i + 2;
      for (; j < subset.length; j++) {
        const c = subset[j];
        if (quote) { if (c === quote) quote = ""; continue; }
        if (c === '"' || c === "'") quote = c;
        else if (c === ">") break;
        else if (c === "<") fail(base + j, "\"<\" inside a declaration in the DOCTYPE.");
      }
      if (j >= subset.length) fail(base + i, "A declaration in the DOCTYPE is never closed with \">\".");
      const decl = subset.slice(i, j + 1);
      if (decl.startsWith("<!ENTITY") && !ENTITY_DECL.test(decl)) fail(base + i, `This entity declaration isn't valid: ${decl.slice(0, 60)}`, "It looks like <!ENTITY name \"value\"> or <!ENTITY name SYSTEM \"file.xml\">.");
      i = j + 1;
    } else {
      fail(base + from, `Unexpected "${subset.slice(i, i + 12)}" in the DOCTYPE.`, "The internal subset may contain <!ENTITY>, <!ELEMENT>, <!ATTLIST>, <!NOTATION>, comments and %references;.");
    }
  }
}

function capital(text: string): string {
  return text.replace(/^an? /, "").replace(/^./, c => c.toUpperCase());
}

/**
 * Decodes an XML file's bytes: a byte-order mark wins, then the encoding the
 * XML declaration names, then UTF-8.
 */
export function decodeXmlBytes(bytes: Uint8Array): { text: string; encoding: string } {
  if (bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf) return { text: new TextDecoder("utf-8").decode(bytes.subarray(3)), encoding: "UTF-8" };
  if (bytes[0] === 0xff && bytes[1] === 0xfe) return { text: new TextDecoder("utf-16le").decode(bytes.subarray(2)), encoding: "UTF-16LE" };
  if (bytes[0] === 0xfe && bytes[1] === 0xff) return { text: new TextDecoder("utf-16be").decode(bytes.subarray(2)), encoding: "UTF-16BE" };
  // UTF-16 without a BOM: "<?" as 3C 00 3F 00 or 00 3C 00 3F.
  if (bytes[0] === 0x3c && bytes[1] === 0x00 && bytes[2] === 0x3f) return { text: new TextDecoder("utf-16le").decode(bytes), encoding: "UTF-16LE" };
  if (bytes[0] === 0x00 && bytes[1] === 0x3c && bytes[3] === 0x3f) return { text: new TextDecoder("utf-16be").decode(bytes), encoding: "UTF-16BE" };
  const head = new TextDecoder("latin1").decode(bytes.subarray(0, 200));
  const declared = /^<\?xml[^>]*\bencoding\s*=\s*["']([A-Za-z][A-Za-z0-9._-]*)["']/.exec(head)?.[1];
  if (declared && !/^utf-?8$/i.test(declared)) {
    try {
      return { text: new TextDecoder(declared).decode(bytes), encoding: declared.toUpperCase() };
    } catch {
      // An encoding the runtime doesn't know: fall through to UTF-8.
    }
  }
  return { text: new TextDecoder("utf-8").decode(bytes), encoding: "UTF-8" };
}
